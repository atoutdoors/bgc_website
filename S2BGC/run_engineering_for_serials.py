DATA_ROOT = Path(r"Z:\S2BGC\data")

# Batch defaults. Set OPEN_WINDOWS to True to open each combined report.
OPEN_WINDOWS = False
SAVE_HUMIDITY_PLOTS = True
OPEN_COMBINED_WINDOW = False
