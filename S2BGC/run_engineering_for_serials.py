def make_all_floats_engineering_profile_plots() -> Path:
    """Create one Turbo-colored trace per float for every engineering parameter."""
    parameters: dict[str, dict[str, dict[str, object]]] = {}
    units: dict[str, str] = {}

    for serial_value in SERIAL_NUMBERS:
        serial = str(serial_value).zfill(4)
        json_dir = DATA_ROOT / serial / "json" / "L0"
        for json_file in sorted(json_dir.glob("*.json")):
            try:
                with json_file.open("r", encoding="utf-8") as handle:
                    data = json.load(handle)
            except (OSError, json.JSONDecodeError) as exc:
                print(f"Skipping {json_file}: {exc}")
                continue

            cycle = data.get("CYCLE_NUMBER")
            engineering = data.get("Engineering_Data", {})
            if cycle is None or not isinstance(engineering, dict):
                continue
            for name, record in engineering.items():
                if not isinstance(record, dict):
                    continue
                value = record.get("value")
                if isinstance(value, bool) or not isinstance(value, (int, float)):
                    continue
                units[name] = str(record.get("unit", ""))
                parameters.setdefault(name, {}).setdefault(serial, {"points": []})
                parameters[name][serial]["points"].append(
                    {"profile": cycle, "value": value, "file": json_file.name}
                )

    chart_data = []
    for name, float_data in sorted(parameters.items()):
        traces = []
        for serial, trace_data in sorted(float_data.items()):
            points = trace_data["points"]
            points.sort(key=lambda point: (point["profile"], point["file"]))
            traces.append({"serial": serial, "points": points})
        chart_data.append({"name": name, "unit": units.get(name, ""), "traces": traces})

    chart_data_json = json.dumps(chart_data)
    html = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>All S2BGC Floats Engineering Profiles</title>
<link href="https://cdn.jsdelivr.net/npm/bootstrap@5.3.3/dist/css/bootstrap.min.css" rel="stylesheet">
<script src="https://cdn.plot.ly/plotly-2.35.2.min.js"></script>
<style>body {{ background:#f6f8fa; }} .plot-card {{ background:white; margin-bottom:24px; }}</style>
</head><body><main class="container py-4">
<h1 class="h3 mb-4">All S2BGC Floats — Engineering Data Across Profiles</h1>
<div id="plots"></div>
<script>
const chartData = {chart_data_json};
const plots = document.getElementById('plots');
const turboPalette = [
  '#30123b', '#4145ab', '#2a78b9', '#22a7a4', '#57c665',
  '#b8df50', '#f5e948', '#fcae3a', '#e94f2b', '#7a0403'
];
const traceColor = index => turboPalette[index % turboPalette.length];
chartData.forEach((chart, chartIndex) => {{
  const card = document.createElement('div');
  card.className = 'card shadow-sm plot-card';
  const plot = document.createElement('div');
  plot.id = 'plot-' + chartIndex;
  plot.style.height = '460px';
  card.appendChild(plot);
  plots.appendChild(card);
  const traces = chart.traces.map((float, floatIndex) => ({{
    name: float.serial,
    x: float.points.map(point => point.profile),
    y: float.points.map(point => point.value),
    text: float.points.map(point => point.file),
    mode: 'lines+markers',
    type: 'scatter',
    marker: {{size: 6, color: traceColor(floatIndex)}},
    line: {{color: traceColor(floatIndex)}},
    hovertemplate: 'Float: %{{fullData.name}}<br>Profile: %{{x}}<br>Value: %{{y}}<br>%{{text}}<extra></extra>'
  }}));
  Plotly.newPlot(plot, traces, {{
    title: chart.name,
    xaxis: {{title: 'Profile / cycle number', dtick: 1}},
    yaxis: {{title: chart.unit ? chart.name + ' (' + chart.unit + ')' : chart.name}},
    hovermode: 'closest',
    legend: {{title: {{text: 'Float'}}}},
    margin: {{t: 60, r: 30, b: 65, l: 85}}
  }}, {{responsive: true}});
}});
</script></main></body></html>"""

    HUMIDITY_PLOT_DIR.mkdir(parents=True, exist_ok=True)
    output_path = HUMIDITY_PLOT_DIR / "all_floats_engineering_profiles.html"
    output_path.write_text(html, encoding="utf-8")
    return output_path


def main() -> None:
    remove_old_vertical_velocity_plots()
    script_path = Path(__file__).with_name("extract_engineering_data.py")

    for serial in SERIAL_NUMBERS:
        command = [
            sys.executable,
            str(script_path),
            str(serial).zfill(4),
            "--root",
            str(DATA_ROOT),
        ]

        if OPEN_WINDOWS:
            command.append("--open-window")
        else:
            command.append("--no-open")

        if SAVE_HUMIDITY_PLOTS:
            command.append("--save-humidity-plot")
        else:
            command.append("--no-save-humidity-plot")

        print(f"Running float {str(serial).zfill(4)}...")
        result = subprocess.run(command, check=False)
        if result.returncode != 0:
            print(f"Float {str(serial).zfill(4)} failed with exit code {result.returncode}")

    combined_path = make_combined_humidity_plot()
    print(f"Saved combined humidity plot to {combined_path.resolve()}")
    if OPEN_COMBINED_WINDOW:
        webbrowser.open_new_tab(combined_path.resolve().as_uri())


    table_path = make_engineering_table()
    print(f"Saved engineering table to {table_path.resolve()}")
    make_float_index_pages()
    profiles_path = make_all_floats_engineering_profile_plots()
    print(f"Saved all-floats engineering profiles to {profiles_path.resolve()}")


if __name__ == "__main__":
    main()
