def remove_old_vertical_velocity_plots() -> None:
    """Remove vertical-velocity files generated by earlier versions."""
    old_files = [HUMIDITY_PLOT_DIR / "vertical_velocity.html"]
    old_files.extend(
        HUMIDITY_PLOT_DIR / str(serial).zfill(4) / f"{str(serial).zfill(4)}_vertical_velocity.html"
        for serial in SERIAL_NUMBERS
    )
    for old_file in old_files:
        try:
            old_file.unlink()
            print(f"Removed old vertical velocity plot: {old_file}")
        except FileNotFoundError:
            pass


