def make_combined_vertical_velocity_plot() -> Path:
    """Create one Plotly vertical-velocity plot with one trace per float."""
    traces: list[dict[str, object]] = []
    for serial_value in SERIAL_NUMBERS:
        serial = str(serial_value).zfill(4)
        points: list[dict[str, object]] = []
        for json_file in sorted((DATA_ROOT / serial / "json" / "L0").glob("*.json")):
            try:
                with json_file.open("r", encoding="utf-8") as handle:
                    data = json.load(handle)
            except (OSError, json.JSONDecodeError) as exc:
                print(f"Skipping {json_file}: {exc}")
                continue

            events = []
            for section in ("Fall", "Rise"):
                for event in data.get(section, []) or []:
                    if not isinstance(event, dict):
                        continue
                    timestamp = parse_time(event.get("TIME"))
                    pressure = event.get("PRES")
                    if timestamp is not None and isinstance(pressure, (int, float)):
                        events.append((timestamp, float(pressure)))
            events.sort(key=lambda item: item[0])
            for previous, current in zip(events, events[1:]):
                seconds = (current[0] - previous[0]).total_seconds()
                if seconds > 0:
                    points.append(
                        {
                            "time": current[0].isoformat(),
                            "velocity": (current[1] - previous[1]) / seconds,
                            "file": json_file.name,
                        }
                    )
        points.sort(key=lambda point: point["time"])
        traces.append({"serial": serial, "points": points})

    traces_json = json.dumps(traces)
    html = f"""<!doctype html>
<html><head><meta charset="utf-8">
<title>All S2BGC Floats Vertical Velocity</title>
<style>body {{ font-family: Arial, sans-serif; margin: 24px; }}</style>
</head><body>
<div id="all-floats-velocity" style="width:100%;height:650px;"></div>
<script src="https://cdn.plot.ly/plotly-2.35.2.min.js"></script>
<script>
const floatData = {traces_json};
const traces = floatData.map(float => ({{
  name: float.serial,
  x: float.points.map(point => point.time),
  y: float.points.map(point => point.velocity),
  text: float.points.map(point => point.file),
  mode: 'lines',
  type: 'scatter',
  hovertemplate: 'Float: %{{fullData.name}}<br>Time: %{{x}}<br>Vertical velocity: %{{y:.4f}} dbar/s<br>%{{text}}<extra></extra>'
}}));
Plotly.newPlot('all-floats-velocity', traces, {{
  title: 'Vertical Velocity — All S2BGC Floats',
  xaxis: {{title: 'Time', type: 'date'}},
  yaxis: {{title: 'Vertical velocity (dbar/s)'}},
  hovermode: 'closest',
  legend: {{title: {{text: 'Float'}}}},
  margin: {{t: 70, r: 30, b: 70, l: 80}}
}}, {{responsive: true}});
</script>
</body></html>"""

    HUMIDITY_PLOT_DIR.mkdir(parents=True, exist_ok=True)
    output_path = HUMIDITY_PLOT_DIR / "vertical_velocity.html"
    output_path.write_text(html, encoding="utf-8")
    return output_path


def parse_time(value: object) -> datetime | None:
    if not value:
        return None
    try:
        return datetime.fromisoformat(str(value).replace("Z", "+00:00"))
    except ValueError:
        return None


def make_engineering_table() -> Path:
    """Create an S2BGC summary table with the Navis table's columns."""
    rows: list[dict[str, object]] = []

    for serial_value in SERIAL_NUMBERS:
        serial = str(serial_value).zfill(4)
        json_dir = DATA_ROOT / serial / "json" / "L0"
        records: list[tuple[Path, dict[str, object]]] = []
        for json_file in sorted(json_dir.glob("*.json")):
            try:
                with json_file.open("r", encoding="utf-8") as handle:
                    records.append((json_file, json.load(handle)))
            except (OSError, json.JSONDecodeError) as exc:
                print(f"Skipping {json_file}: {exc}")

        if not records:
            continue

        report_times = [
            parse_time(data.get("FILE_CREATION_DATE"))
            for _, data in records
        ]
        report_times = [value for value in report_times if value is not None]
        if not report_times:
            continue
        first_report = min(report_times)
        latest_report = max(report_times)
        latest_data = max(
            records,
            key=lambda item: parse_time(item[1].get("FILE_CREATION_DATE"))
            or datetime.min.replace(tzinfo=timezone.utc),
        )[1]

        fall = latest_data.get("Fall") or []
        rise = latest_data.get("Rise") or []
        park_pressure = None
        for event in reversed(fall):
            if isinstance(event, dict) and event.get("description") == "Drift begin":
                park_pressure = event.get("PRES")
                break
        if park_pressure is None:
            pressures = [event.get("PRES") for event in fall if isinstance(event, dict)]
            park_pressure = max((value for value in pressures if isinstance(value, (int, float))), default=None)

        profile_pressures = [
            event.get("PRES") for event in rise if isinstance(event, dict)
        ]
        deep_profile_pressure = max(
            (value for value in profile_pressures if isinstance(value, (int, float))),
            default=None,
        )

        gps = latest_data.get("GPS") or []
        gps_start = parse_time(gps[0].get("TIME")) if gps and isinstance(gps[0], dict) else None
        gps_end = parse_time(gps[-1].get("TIME")) if gps and isinstance(gps[-1], dict) else None
        cycle_length = str(gps_end - gps_start) if gps_start and gps_end else ""
        age_days = (latest_report.date() - first_report.date()).days
        days_since = (date.today() - latest_report.date()).days

        rows.append(
            {
                "serial": serial,
                "wmo": latest_data.get("WMO_ID_NUMBER", ""),
                "park": park_pressure,
                "deep": deep_profile_pressure,
                "first": first_report.date().isoformat(),
                "latest": latest_report.date().isoformat(),
                "age": age_days,
                "length": cycle_length,
                "cycle": latest_data.get("CYCLE_NUMBER", ""),
                "since": days_since,
            }
        )

    headers = [
        "Serial Number",
        "WMO ID",
        "Last Park Pressure (dbars)",
        "Last Deep Profile Pressure (dbars)",
        "First Report",
        "Latest Report",
        "Age in Days at Latest Report",
        "Latest Cycle Length",
        "Cycle Number",
        "Days Since Last Report",
    ]
    body_rows = []
    for row in sorted(rows, key=lambda item: str(item["serial"])):
        serial = escape(str(row["serial"]))
        serial_link = f'<a href="S2BGC/{serial}/{serial}_engineering_profiles.html" target="_blank">{serial}</a>'
        body_rows.append(
            "<tr>"
            + f"<td>{serial_link}</td>"
            + "".join(
                f"<td>{escape(str(row[field]))}</td>"
                for field in [
                    "wmo", "park", "deep", "first", "latest", "age",
                    "length", "cycle", "since",
                ]
            )
            + "</tr>"
        )

    header_html = "".join(f"<th>{escape(header)}</th>" for header in headers)
    html = f"""<!doctype html>
<html><head><meta charset="utf-8">
<link href="https://cdn.datatables.net/1.11.5/css/jquery.dataTables.min.css" rel="stylesheet">
<title>S2BGC Engineering Table</title></head>
<body style="margin:0; padding:24px; text-align:center; font-family:Arial,sans-serif; background:#f6f8fa;">
<div style="max-width:1400px; margin:0 auto;"><table border="1" class="dataframe" id="table">
<thead><tr>{header_html}</tr></thead><tbody>{''.join(body_rows)}</tbody>
</table></div>
<script src="https://code.jquery.com/jquery-3.6.0.slim.min.js"></script>
<script src="https://cdn.datatables.net/1.11.5/js/jquery.dataTables.min.js"></script>
<script>$(document).ready(function () {{ $('#table').DataTable(); }});</script>
</body></html>"""

    HUMIDITY_PLOT_DIR.mkdir(parents=True, exist_ok=True)
    output_path = HUMIDITY_PLOT_DIR / "engineeringtable.html"
    output_path.write_text(html, encoding="utf-8")
    return output_path


