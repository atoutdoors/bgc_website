def log(message: str) -> None:
    """Print and persist diagnostic messages for scheduled runs."""
    print(message, flush=True)
    try:
        with RUN_LOG_PATH.open("a", encoding="utf-8") as handle:
            handle.write(message + "\n")
    except OSError as exc:
        print(f"WARNING: could not write diagnostic log {RUN_LOG_PATH}: {exc}", flush=True)


def report_progress(percent: int, message: str) -> None:
    """Print a compact progress bar for the hourly wrapper and terminal runs."""
    percent = max(0, min(100, percent))
    filled = percent // 2
    bar = "#" * filled + "-" * (50 - filled)
    line = f"[{bar}] {percent:3d}% - {message}"
    print(line, end="\r", flush=True)
    try:
        with RUN_LOG_PATH.open("a", encoding="utf-8") as handle:
            handle.write(line + "\n")
    except OSError as exc:
        print(f"WARNING: could not write diagnostic log {RUN_LOG_PATH}: {exc}", flush=True)


def validate_paths() -> None:
    """Fail early with an actionable message for missing or inaccessible paths."""
    try:
        if not DATA_ROOT.is_dir():
            raise FileNotFoundError(
                f"data root does not exist or is not a directory: {DATA_ROOT}"
            )
        HUMIDITY_PLOT_DIR.mkdir(parents=True, exist_ok=True)
    except PermissionError as exc:
        raise PermissionError(
            "Access denied while checking S2BGC paths. "
            f"Data root: {DATA_ROOT}; output directory: {HUMIDITY_PLOT_DIR}. "
            "If this is a scheduled task, use UNC paths and grant the task "
            "account share permission."
        ) from exc


def remove_old_vertical_velocity_plots() -> None:
    """Remove vertical-velocity files generated by earlier versions."""
    # Delete obsolete files so old charts are not mistaken for current output.
    old_files = [HUMIDITY_PLOT_DIR / "vertical_velocity.html"]
    old_files.extend(
        HUMIDITY_PLOT_DIR / str(serial).zfill(4) / f"{str(serial).zfill(4)}_vertical_velocity.html"
        for serial in SERIAL_NUMBERS
    )
    for old_file in old_files:
        try:
            old_file.unlink()
            print(f"Removed old vertical velocity plot: {old_file}")
        except FileNotFoundError:
            pass


